# Проверка наличия python3
if ! command -v python3 &> /dev/null; then
    echo -e "${RED}Ошибка: python3 не найден в системе.${NC}"
    echo "Пожалуйста, установите python3 (например: sudo apt install python3 или sudo dnf install python3)"
    exit 1
fi

UNINSTALL=false
CUSTOM_PATH=""

for arg in "$@"; do
    case "$arg" in
        --uninstall|-u)
            UNINSTALL=true
            ;;
        *)
            if [ -z "$CUSTOM_PATH" ]; then
                CUSTOM_PATH="$arg"
            fi
            ;;
    esac
done

# Поиск пути к Draw.IO
find_drawio_asar() {
    # 1. По переданному пользователем пути
    if [ -n "$1" ]; then
        if [ -f "$1/resources/app.asar" ]; then
            echo "$1/resources/app.asar"
            return 0
        elif [ -f "$1/app.asar" ]; then
            echo "$1/app.asar"
            return 0
        elif [ -f "$1" ]; then
            echo "$1"
            return 0
        fi
    fi

    # 2. По расположению бинарника в PATH
    for cmd in drawio draw.io; do
        if command -v "$cmd" &> /dev/null; then
            BIN_PATH=$(readlink -f "$(which "$cmd")" 2>/dev/null || which "$cmd")
            BIN_DIR=$(dirname "$BIN_PATH")
            if [ -f "$BIN_DIR/resources/app.asar" ]; then
                echo "$BIN_DIR/resources/app.asar"
                return 0
            fi
            if [ -f "$BIN_DIR/app.asar" ]; then
                echo "$BIN_DIR/app.asar"
                return 0
            fi
        fi
    done

    # 3. По стандартным каталогам Linux
    CANDIDATES=(
        "/opt/drawio/resources/app.asar"
        "/opt/draw.io/resources/app.asar"
        "/usr/lib/drawio/resources/app.asar"
        "/usr/share/drawio/resources/app.asar"
        "$HOME/.local/share/drawio/resources/app.asar"
        "$HOME/Applications/drawio/resources/app.asar"
    )

    for p in "${CANDIDATES[@]}"; do
        if [ -f "$p" ]; then
            echo "$p"
            return 0
        fi
    done

    return 1
}

ASAR_FILE=$(find_drawio_asar "$CUSTOM_PATH") || true

if [ -z "$ASAR_FILE" ]; then
    echo -e "${YELLOW}Draw.IO не найден в стандартных каталогах (/opt/drawio, etc.).${NC}"
    echo -n "Введите путь к папке Draw.IO или к файлу app.asar: "
    read -r USER_INPUT
    ASAR_FILE=$(find_drawio_asar "$USER_INPUT") || true
    if [ -z "$ASAR_FILE" ]; then
        echo -e "${RED}Ошибка: app.asar не найден по указанному пути.${NC}"
        exit 1
    fi
fi

ASAR_DIR=$(dirname "$ASAR_FILE")
echo -e "${GREEN}✓ Найден Draw.IO:${NC} $ASAR_FILE"

# Проверка прав на запись
if [ "$EUID" -ne 0 ] && [ ! -w "$ASAR_DIR" ]; then
    echo -e "${YELLOW}Для изменения файлов в $ASAR_DIR требуются права администратора (sudo).${NC}"
    echo "Перезапуск через sudo..."
    exec sudo "$0" "$@"
fi

# Режим отката (uninstall)
if [ "$UNINSTALL" = true ]; then
    BAK_FILE="$ASAR_FILE.bak"
    if [ -f "$BAK_FILE" ]; then
        echo "Закрытие запущенных процессов drawio..."
        pkill -x drawio 2>/dev/null || true
        cp -f "$BAK_FILE" "$ASAR_FILE"
        echo -e "${GREEN}✓ Оригинальный Draw.IO успешно восстановлен из резервной копии!${NC}"
        exit 0
    else
        echo -e "${RED}Резервная копия $BAK_FILE не найдена.${NC}"
        exit 1
    fi
fi

# Закрытие запущенного Draw.IO
echo "Проверка запущенных процессов drawio..."
pkill -x drawio 2>/dev/null || true
sleep 1

